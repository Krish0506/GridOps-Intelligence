"""Top-level orchestration for synthetic data generation.

All data is synthetic; the ``synthetic`` marker appears in every row and the
``synthetic_manifest.json`` manifest records provenance.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

from data_engineering.generators.assets import (
    generate_circuit_breakers,
    generate_feeders,
    generate_substations,
    generate_transformers,
)
from data_engineering.generators.base import asset_id, write_csv, write_json
from data_engineering.generators.config import (
    ASSET_TABLES,
    DEFAULT_SEED,
    OUTPUT_DIR,
    REFERENCE_DATE,
    TABLE_FIELDNAMES,
    TABLES,
)
from data_engineering.generators.failures import generate_failures
from data_engineering.generators.inspections import generate_inspections
from data_engineering.generators.maintenance import generate_work_orders
from data_engineering.generators.telemetry import generate_telemetry, inject_abnormal_telemetry
from data_engineering.generators.validation import validate_all
from data_engineering.generators.weather import generate_weather


def generate_all(output_dir: Path | str | None = None) -> dict:
    """Generate every synthetic dataset and return the manifest dict."""
    rng = random.Random(DEFAULT_SEED)
    output_dir = Path(output_dir) if output_dir is not None else OUTPUT_DIR

    substations = generate_substations(rng)
    breakers = generate_circuit_breakers(rng, substations)
    transformers = generate_transformers(rng, substations)
    feeders = generate_feeders(rng, substations)
    assets = substations + breakers + transformers + feeders
    assets_by_id = {asset_id(asset): asset for asset in assets}

    telemetry = generate_telemetry(rng, assets)
    failures, risk_scores = generate_failures(rng, assets, telemetry)
    # Elevated telemetry rows around failure timestamps (feature signal only).
    inject_abnormal_telemetry(rng, assets_by_id, failures, telemetry)
    work_orders = generate_work_orders(rng, assets, failures, risk_scores)
    inspections = generate_inspections(rng, assets, risk_scores)
    weather = generate_weather(rng)

    datasets = [
        ("transformers", transformers),
        ("substations", substations),
        ("circuit_breakers", breakers),
        ("feeders", feeders),
        ("asset_telemetry", telemetry),
        ("work_orders", work_orders),
        ("inspections", inspections),
        ("failures", failures),
        ("weather", weather),
    ]
    files: dict[str, dict] = {}
    for name, rows in datasets:
        write_csv(output_dir / f"{name}.csv", rows, TABLE_FIELDNAMES[name])
        # Store portable, relative paths so the manifest never leaks local paths.
        files[name] = {"path": f"{name}.csv", "rows": len(rows)}

    counts = {name: files[name]["rows"] for name in files}
    results = validate_all(output_dir)
    manifest = {
        "name": "gridops-synthetic-utility-data",
        "generator": "data_engineering.generators.generate_all",
        "reference_date": REFERENCE_DATE.isoformat(),
        "seed": DEFAULT_SEED,
        "counts": counts,
        "total_assets": sum(counts[table] for table in ASSET_TABLES),
        "files": files,
        "validation": {
            table: {
                "ok": result.ok,
                "errors": len(result.errors),
                "missing_fields": len(result.missing_fields),
                "duplicates": len(result.duplicates),
                "completeness": round(result.completeness, 4),
            }
            for table, result in results.items()
        },
        "synthetic": (
            "All records are synthetic. No real utility or operational data is included; "
            "no DTE confidential or operational details are used."
        ),
        "notes": [
            "Synthetic only; generated by GridOps Intelligence data_engineering.generators.",
            "No DTE confidential or operational data is used.",
            "Failure labels are isolated to failures.csv; telemetry contains no target leakage.",
        ],
    }
    manifest_path = output_dir / "synthetic_manifest.json"
    manifest["files"]["synthetic_manifest"] = {"path": manifest_path.name, "rows": 0}
    write_json(manifest_path, manifest)
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate and validate synthetic utility data.")
    parser.add_argument("--output", type=Path, default=None, help="Output directory (default: data/generated)")
    args = parser.parse_args()

    output_dir = args.output if args.output is not None else OUTPUT_DIR
    manifest = generate_all(output_dir)
    print(f"Output directory: {output_dir.resolve()}")
    for name in TABLES:
        print(f"  {name}: {manifest['counts'][name]} rows")
    print("Validation summary:")
    errors = 0
    for table in sorted(manifest["validation"]):
        summary = manifest["validation"][table]
        print(
            f"  {table}: ok={summary['ok']} errors={summary['errors']} "
            f"missing_fields={summary['missing_fields']} duplicates={summary['duplicates']} "
            f"completeness={summary['completeness']}"
        )
        errors += summary["errors"]
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main())
